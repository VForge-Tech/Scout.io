class LocalEmbeddingService:
    """Interface-compatible stand-in for EmbeddingService backed by a local
    sentence-transformers bi-encoder, so the eval runs without an embedding
    provider API. Replaced by real embeddings so precision is meaningful."""

    def __init__(self, model: str = "all-MiniLM-L6-v2"):
        from sentence_transformers import SentenceTransformer

        self._model = SentenceTransformer(model)
        self.dimensions = self._model.get_sentence_embedding_dimension()

    def embed_text(self, text: str) -> list[float]:
        return self._model.encode(text, normalize_embeddings=True).tolist()

    def embed_texts(self, texts: list[str]) -> list[list[float]]:
        if not texts:
            return []
        return self._model.encode(texts, normalize_embeddings=True).tolist()

    def embed_query(self, query: str) -> list[float]:
        return self.embed_text(query)

