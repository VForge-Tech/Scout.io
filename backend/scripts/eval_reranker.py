def _make_engine(reranker_enabled: bool, reranker_url: str, qdrant_client: QdrantClient, org_id: str) -> KnowledgeEngine:
    settings = get_settings()
    settings.reranker_enabled = reranker_enabled
    settings.reranker_url = reranker_url

    store = QdrantStore(
        collection_name=f"eval_{org_id}",
        embedding_service=LocalEmbeddingService(),
    )
    # Replace the client with the caller-provided in-process one
    store.client = qdrant_client
    return KnowledgeEngine(
        qdrant_store=store,
        reranker_client=RerankerClient(url=reranker_url),
    )


def _index(engine: KnowledgeEngine, org_id: str, bot_id: str) -> None:
    chunks = [
        (text, {"source_id": key, "organization_id": org_id, "chatbot_id": bot_id, "chunk_index": i})
        for i, (key, text) in enumerate(CORPUS)
    ]
    engine.index_chunks(chunks)


def _reciprocal_rank(results: list[dict], relevant: list[str]) -> float:
    for i, r in enumerate(results):
        if r["source_id"] in relevant:
            return 1.0 / (i + 1)
    return 0.0


def _ndcg_at_k(results: list[dict], relevant: list[str], k: int) -> float:
    dcg = 0.0
    for i, r in enumerate(results[:k]):
        if r["source_id"] in relevant:
            dcg += 1.0 / (i + 2)  # log2(i+2)
    idcg = sum(1.0 / (i + 2) for i in range(min(len(relevant), k)))
    return dcg / idcg if idcg > 0 else 0.0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--reranker-url", default=os.getenv("RERANKER_URL", "http://127.0.0.1:8082"))
    ap.add_argument("--qdrant-url", default=None, help="Remote Qdrant URL; omit for in-process local Qdrant")
    ap.add_argument("--top-k", type=int, default=5)
    args = ap.parse_args()

    tmpdir = tempfile.mkdtemp(prefix="scout_eval_")
    settings = get_settings()
    org_id = "eval-org"
    bot_id = "eval-bot"

    qdrant = QdrantClient(path=os.path.join(tmpdir, "qdrant")) if not args.qdrant_url else QdrantClient(url=args.qdrant_url)

    print(f"Reranker URL : {args.reranker_url}")
    print(f"Qdrant       : {'local (in-process)' if not args.qdrant_url else args.qdrant_url}")
    print(f"Top-K        : {args.top_k}\n")

    metrics = {"mrr": [], "ndcg3": [], "ndcg5": []}
    for label, enabled in (("Qdrant-only", False), ("Qdrant+Reranker", True)):
        engine = _make_engine(enabled, args.reranker_url, qdrant, org_id)
        _index(engine, org_id, bot_id)
        per_query = {"mrr": [], "ndcg3": [], "ndcg5": []}
        for query, relevant in QUERIES:
            results = engine.retrieve(
                query=query,
                organization_id=org_id,
                chatbot_id=bot_id,
                top_k=args.top_k,
            )
            if not results:
                continue
            per_query["mrr"].append(_reciprocal_rank(results, relevant))
            per_query["ndcg3"].append(_ndcg_at_k(results, relevant, 3))
            per_query["ndcg5"].append(_ndcg_at_k(results, relevant, 5))
        avg = {
            k: (sum(v) / len(v) if v else 0.0)
            for k, v in per_query.items()
        }
        metrics[label] = avg
        print(f"{label:<16} MRR@K={avg['mrr']:.3f}  nDCG@3={avg['ndcg3']:.3f}  nDCG@5={avg['ndcg5']:.3f}")

    print("\nPer-query MRR@K comparison:")
    print(f"{'Query':<52} {'Qdrant':>8} {'Qd+Rerank':>10}")
    baseline_engine = _make_engine(False, args.reranker_url, qdrant, org_id)
    reranked_engine = _make_engine(True, args.reranker_url, qdrant, org_id)
    _index(baseline_engine, org_id, bot_id)
    for query, relevant in QUERIES:
        b = baseline_engine.retrieve(query=query, organization_id=org_id, chatbot_id=bot_id, top_k=args.top_k)
        r = reranked_engine.retrieve(query=query, organization_id=org_id, chatbot_id=bot_id, top_k=args.top_k)
        print(f"{query:<52} {_reciprocal_rank(b, relevant):8.3f} {_reciprocal_rank(r, relevant):10.3f}")

    return 0


if __name__ == "__main__":
    sys.exit(main())