"""Retrieval precision measurement: Qdrant-only vs Qdrant + cross-encoder reranker.

Constructs a small knowledge base with ground-truth relevant chunks, then runs
the backend's KnowledgeEngine.retrieve() with the reranker disabled and enabled
and reports MRR@K / nDCG@K for each.

Run against a local reranker service instance:
    cd services/reranker
    python -m uvicorn app.main:app --host 127.0.0.1 --port 8082 &
    cd ../../backend
    RERANKER_ENABLED=true RERANKER_URL=http://127.0.0.1:8082 \
        QDRANT_URL=... python ../scripts/eval_reranker.py

Qdrant is used in local (in-process) mode so the whole eval runs without Docker;
QDRANT_URL should point at a running Qdrant or be empty to use the on-disk local
client. The KB is written to a temp collection and cleaned up afterwards.
"""

